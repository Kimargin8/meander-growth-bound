int main(int argc,char**argv) {
    if(argc<6||argc>8) {std::cerr<<"k p q rounds upper_numerator_scale [output prefix] [--fold]\n";return 2;}
    bool fold=argc==8 && std::string(argv[7])=="--fold";
    if(argc==8&&!fold) throw std::invalid_argument("unrecognised option");
    int k=std::stoi(argv[1]),p=std::stoi(argv[2]),q=std::stoi(argv[3]),rounds=std::stoi(argv[4]);
    Word scale=std::stoull(argv[5]);
    if(k<1||k>16||p<q||q<1||p>200||rounds<1||rounds>2000||!scale||scale>1000000000000ULL)
        throw std::invalid_argument("invalid parameters");
    const auto start=std::chrono::steady_clock::now();
    Graph g(k,fold);
    const auto n=g.rows.size();
    // Limit all raw integer sums to 62 bits, for every input p,q.
    Word h=(Word(1)<<61)/(Word(p+q)*(p+q));
    Word unit=std::bit_floor(h);
    std::vector<Word> v(n+1,unit),next(n+1);
    v.back()=0;
    auto act=[&]() {
        Word maximum=0;
        for(std::size_t i=0;i<n;++i) {
            const auto &a=g.rows[i];
            Word t=p==1&&q==1?v[a[0]]+v[a[1]]+v[a[2]]+v[a[3]]:
              Word(p)*p*v[a[0]]+Word(p)*q*(v[a[1]]+v[a[2]])+Word(q)*q*v[a[3]];
            next[i]=t;maximum=std::max(maximum,t);
        }
        return maximum;
    };
    for(int it=0;it<rounds;++it) {
        Word mx=act();int shift=0;
        while((mx>>shift)>unit) ++shift;
        for(std::size_t i=0;i<n;++i) next[i]>>=shift;
        v.swap(next);
    }
    act();
    Word high=0,vmin=v[0];
    for(std::size_t i=0;i<n;++i) {
        if(!v[i]) throw std::domain_error("nonpositive witness");
        Wide den=Wide(p)*q*v[i];
        Word bound=static_cast<Word>((Wide(next[i])*scale+den-1)/den);
        high=std::max(high,bound);vmin=std::min(vmin,v[i]);
    }
    for(std::size_t i=0;i<n;++i)
        if(Wide(next[i])*scale>Wide(high)*p*q*v[i]) throw std::logic_error("inequality");
    if(argc>=7) {
        std::string prefix=argv[6];v.pop_back();
        dump(prefix+".states",g.states);dump(prefix+".vector",v);
    }
    std::cout<<"{\"k\":"<<k<<",\"p\":"<<p<<",\"q\":"<<q<<",\"rounds\":"<<rounds
             <<",\"folded\":"<<(fold?"true":"false")<<",\"states\":"<<n<<",\"den\":"<<scale<<",\"upper\":"<<high
             <<",\"v_empty\":"<<v[0]<<",\"v_min\":"<<vmin<<",\"seconds\":"
             <<std::chrono::duration<double>(std::chrono::steady_clock::now()-start).count()<<"}\n";
}
