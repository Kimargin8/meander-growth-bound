// Build a partial pairing of the 2k nearest ends and certify a one-sided growth bound.
#include <algorithm>
#include <array>
#include <bit>
#include <chrono>
#include <cstdint>
#include <fstream>
#include <iostream>
#include <limits>
#include <stdexcept>
#include <string>
#include <vector>

using Word=std::uint64_t;
using Index=std::uint32_t;
using Wide=__uint128_t;
constexpr Index none=std::numeric_limits<Index>::max();
using Row=std::array<Index,4>;

// Store just an index in each hash slot. Keys already live in the BFS list.
class StateIndex {
    std::vector<Index> slots=std::vector<Index>(64,none);
    const std::vector<Word>& keys;
    static Word hash(Word x) {
        x^=x>>30;x*=0xbf58476d1ce4e5b9ULL;
        x^=x>>27;x*=0x94d049bb133111ebULL;
        return x^(x>>31);
    }
    size_t locate(Word key) const {
        size_t mask=slots.size()-1,pos=hash(key)&mask;
        while(slots[pos]!=none && keys[slots[pos]]!=key) pos=(pos+1)&mask;
        return pos;
    }
public:
    explicit StateIndex(const std::vector<Word>& k):keys(k) {slots[0]=0;}
    std::pair<Index,bool> find_or_add(Word key) {
        if(keys.size()>=none) throw std::overflow_error("state index overflow");
        if(keys.size()*4>slots.size()*3) {
            slots.assign(slots.size()*2,none);
            for(Index i=0;i<keys.size();++i) slots[locate(keys[i])]=i;
        }
        auto &entry=slots[locate(key)];
        if(entry!=none) return {entry,false};
        entry=static_cast<Index>(keys.size());return {entry,true};
    }
};

Word reflect(Word x,int width) {
    // Reversing all bits reverses the order of the ends and exchanges open/close.
    x=((x>>1)&0x5555555555555555ULL)|((x&0x5555555555555555ULL)<<1);
    x=((x>>2)&0x3333333333333333ULL)|((x&0x3333333333333333ULL)<<2);
    x=((x>>4)&0x0f0f0f0f0f0f0f0fULL)|((x&0x0f0f0f0f0f0f0f0fULL)<<4);
    return __builtin_bswap64(x)>>(64-2*width);
}

struct Graph {
    std::vector<Word> states{0};
    std::vector<Row> rows;
    Graph(int k,bool fold) {
        const int width=2*k;
        StateIndex index(states);
        // Capacity hints only. The graph itself is generated by its transitions.
        if(fold&&k>=14) {
            size_t hint=k==14?10500000:(k==15?41000000:159000000);
            states.reserve(hint);rows.reserve(hint);
        }
        for (std::size_t source=0; source<states.size(); ++source) {
            std::array<int,32> stack{}, mate{};
            mate.fill(-1);
            int height=0;
            Word word=states[source];
            for (int i=0;i<width;++i) {
                int c=(word>>(2*i))&3;
                if(c==1) stack[height++]=i;
                else if(c==2) {
                    if(!height) throw std::logic_error("unbalanced arc");
                    const int p=stack[--height]; mate[i]=p;mate[p]=i;
                } else if(c!=0) throw std::logic_error("invalid letter");
            }
            if(height) throw std::logic_error("unclosed arc");
            Row row{};
            for(int op=0;op<4;++op) {
                if(op==3 && mate[k-1]==k) {row[op]=none;continue;}
                auto relocate=[&](int i) {
                    if(op==1) return i+1;
                    if(op==2) return i-1;
                    if(op==0) return i+(i<k?-1:1);
                    return i==k-1||i==k?-1:i+(i<k?1:-1);
                };
                Word next=0;
                auto arc=[&](int a,int b) {
                    if(a>b) std::swap(a,b);
                    if(a>=0 && b<width) next|=(Word(1)<<(2*a))|(Word(2)<<(2*b));
                };
                for(int i=0;i<width;++i)
                    if(mate[i]>i) arc(relocate(i),relocate(mate[i]));
                if(op==0) arc(k-1,k);
                if(op==3 && mate[k-1]>=0 && mate[k]>=0) arc(relocate(mate[k-1]),relocate(mate[k]));
                if(fold) next=std::min(next,reflect(next,width));
                auto [target,added]=index.find_or_add(next);
                if(added) states.push_back(next);
                row[op]=target;
            }
            rows.push_back(row);
        }
        // The zero sentinel permits three common operations and one conditional close.
        for(auto &row:rows) if(row[3]==none) row[3]=static_cast<Index>(rows.size());
    }
};

void dump(const std::string& file,const auto& data) {
    std::ofstream out(file,std::ios::binary);
    out.write(reinterpret_cast<const char*>(data.data()),data.size()*sizeof(data[0]));
    if(!out) throw std::runtime_error("write error "+file);
}

